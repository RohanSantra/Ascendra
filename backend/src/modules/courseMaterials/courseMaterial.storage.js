import { v2 as cloudinary } from "cloudinary";

import { randomUUID } from "node:crypto";
import path from "node:path";

import {
    HTTP_STATUS,
    ERROR_CODES
} from "../../core/constants/index.js";

import AppError from "../../core/errors/AppError.js";


/**
 * Maximum permitted course material size.
 *
 * 500 MB is the application-level limit.
 */
export const MAX_COURSE_MATERIAL_SIZE = 500 * 1024 * 1024;


/**
 * Supported course material formats.
 *
 * Raw files are stored using Cloudinary's raw resource type.
 * Video files are stored using Cloudinary's video resource type.
 */
const SUPPORTED_FILES = {
    ".pdf": {
        mimeType: "application/pdf",
        resourceType: "raw"
    },
    ".doc": {
        mimeType: "application/msword",
        resourceType: "raw"
    },
    ".docx": {
        mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        resourceType: "raw"
    },
    ".ppt": {
        mimeType: "application/vnd.ms-powerpoint",
        resourceType: "raw"
    },
    ".pptx": {
        mimeType: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        resourceType: "raw"
    },
    ".mp4": {
        mimeType: "video/mp4",
        resourceType: "video"
    },
    ".webm": {
        mimeType: "video/webm",
        resourceType: "video"
    },
    ".mov": {
        mimeType: "video/quicktime",
        resourceType: "video"
    },
    ".avi": {
        mimeType: "video/x-msvideo",
        resourceType: "video"
    }
};


/**
 * Creates a standardized storage error.
 *
 * @param {string} message
 * @param {number} statusCode
 * @param {string} code
 * @returns {AppError}
 */
const createStorageError = (
    message,
    statusCode = HTTP_STATUS.BAD_REQUEST,
    code = ERROR_CODES.VALIDATION_ERROR
) => {
    return new AppError(message, statusCode, code);
};


/**
 * Configures the Cloudinary SDK.
 *
 * Credentials are loaded exclusively from environment variables.
 *
 * @returns {Object}
 */
const configureCloudinary = () => {
    const cloudName = process.env.CLOUDINARY_CLOUD_NAME;
    const apiKey = process.env.CLOUDINARY_API_KEY;
    const apiSecret = process.env.CLOUDINARY_API_SECRET;

    if (!cloudName || !apiKey || !apiSecret) {
        throw createStorageError(
            "Cloudinary storage is not configured.",
            HTTP_STATUS.INTERNAL_SERVER_ERROR,
            ERROR_CODES.INTERNAL_SERVER_ERROR
        );
    }

    cloudinary.config({
        cloud_name: cloudName,
        api_key: apiKey,
        api_secret: apiSecret,
        secure: true
    });

    return {
        cloudName,
        apiKey,
        apiSecret
    };
};


/**
 * Validates organisation and course identifiers.
 *
 * @param {string} orgId
 * @param {string} courseId
 * @returns {void}
 */
const validateStorageOwnership = (orgId, courseId) => {
    if (
        typeof orgId !== "string" ||
        typeof courseId !== "string" ||
        !/^[a-f\d]{24}$/i.test(orgId) ||
        !/^[a-f\d]{24}$/i.test(courseId)
    ) {
        throw createStorageError(
            "Invalid organisation or course identifier."
        );
    }
};


/**
 * Generates the Cloudinary asset folder for a course.
 *
 * Dynamic folder mode separates the asset's organizational
 * folder from its public identifier.
 *
 * @param {string} orgId
 * @param {string} courseId
 * @returns {string}
 */
const getCourseMaterialAssetFolder = (orgId, courseId) => {
    validateStorageOwnership(orgId, courseId);

    return `ascendra/course-materials/${orgId}/${courseId}`;
};


/**
 * Validates a Cloudinary public identifier generated by this module.
 *
 * Raw public IDs contain their file extension.
 * Video public IDs do not contain a file extension.
 *
 * @param {string} publicId
 * @param {string} resourceType
 * @returns {boolean}
 */
const isValidCourseMaterialPublicId = (
    publicId,
    resourceType
) => {
    if (
        typeof publicId !== "string" ||
        !["raw", "video"].includes(resourceType)
    ) {
        return false;
    }

    const uuidPattern =
        /^[a-f\d]{8}-[a-f\d]{4}-4[a-f\d]{3}-[89ab][a-f\d]{3}-[a-f\d]{12}$/i;

    if (resourceType === "video") {
        return uuidPattern.test(publicId);
    }

    return new RegExp(
        `${uuidPattern.source.replace(/^\^|\$$/g, "")}\\.[a-z0-9]+$`,
        "i"
    ).test(publicId);
};


/**
 * Validates the requested file extension, MIME type and size.
 *
 * The extension and MIME type must match the supported file
 * definition. These checks validate metadata, not file contents.
 *
 * @param {string} originalName
 * @param {string} mimeType
 * @param {number} size
 * @returns {Object}
 */
export const validateCourseMaterialFile = (
    originalName,
    mimeType,
    size
) => {
    if (
        typeof originalName !== "string" ||
        !originalName.trim() ||
        originalName.length > 255
    ) {
        throw createStorageError(
            "A valid original filename is required."
        );
    }

    if (
        typeof mimeType !== "string" ||
        !mimeType.trim()
    ) {
        throw createStorageError(
            "A valid MIME type is required."
        );
    }

    if (
        !Number.isSafeInteger(size) ||
        size < 1 ||
        size > MAX_COURSE_MATERIAL_SIZE
    ) {
        throw createStorageError(
            "File size must be between 1 byte and 500 MB."
        );
    }

    const extension = path.extname(originalName).toLowerCase();

    const fileDefinition = SUPPORTED_FILES[extension];

    if (!fileDefinition) {
        throw createStorageError(
            "This course material file format is not supported."
        );
    }

    if (fileDefinition.mimeType !== mimeType) {
        throw createStorageError(
            "File extension and MIME type do not match."
        );
    }

    return {
        extension,
        mimeType: fileDefinition.mimeType,
        resourceType: fileDefinition.resourceType
    };
};


/**
 * Creates a signed Cloudinary upload configuration.
 *
 * The browser uploads directly to Cloudinary.
 * The Express server never receives the file binary.
 *
 * Cloudinary dynamic folder mode is used:
 * - asset_folder controls organizational placement.
 * - public_id independently identifies the uploaded asset.
 *
 * @param {Object} options
 * @param {string} options.orgId
 * @param {string} options.courseId
 * @param {string} options.originalName
 * @param {string} options.mimeType
 * @param {number} options.size
 *
 * @returns {Object}
 */
export const createCourseMaterialUploadSignature = ({
    orgId,
    courseId,
    originalName,
    mimeType,
    size
}) => {
    const {
        cloudName,
        apiKey,
        apiSecret
    } = configureCloudinary();

    validateStorageOwnership(orgId, courseId);

    const fileDefinition = validateCourseMaterialFile(
        originalName,
        mimeType,
        size
    );

    const assetFolder = getCourseMaterialAssetFolder(
        orgId,
        courseId
    );

    /**
     * Cloudinary raw public IDs include the file extension.
     * Video public IDs are generated without an extension.
     */
    const publicId = fileDefinition.resourceType === "raw"
        ? `${randomUUID()}${fileDefinition.extension}`
        : randomUUID();

    const timestamp = Math.floor(Date.now() / 1000);

    /**
     * These parameters are signed on the server and must be
     * submitted unchanged by the browser.
     *
     * asset_folder is used instead of folder because this
     * application uses Cloudinary dynamic folder mode.
     */
    const signedParameters = {
        asset_folder: assetFolder,
        public_id: publicId,
        timestamp,
        type: "authenticated",
        overwrite: false,
        unique_filename: false
    };

    const signature = cloudinary.utils.api_sign_request(
        signedParameters,
        apiSecret
    );

    return {
        cloudName,
        apiKey,
        timestamp,
        signature,
        assetFolder,
        publicId,
        resourceType: fileDefinition.resourceType,
        deliveryType: "authenticated",
        maxFileSize: MAX_COURSE_MATERIAL_SIZE
    };
};


/**
 * Verifies a completed Cloudinary upload.
 *
 * The resource is retrieved from Cloudinary's authenticated
 * Admin API rather than trusting browser-submitted metadata.
 *
 * The upload intent separately verifies that this public ID
 * was generated for the correct organisation, course and user.
 *
 * @param {Object} options
 * @param {string} options.publicId
 * @param {string} options.resourceType
 * @param {string} options.orgId
 * @param {string} options.courseId
 * @param {number} options.expectedSize
 * @param {string} options.mimeType
 * @param {string} options.originalName
 *
 * @returns {Promise<Object>}
 */
export const verifyCourseMaterialUpload = async ({
    publicId,
    resourceType,
    orgId,
    courseId,
    expectedSize,
    mimeType,
    originalName
}) => {
    configureCloudinary();

    validateStorageOwnership(orgId, courseId);

    const fileDefinition = validateCourseMaterialFile(
        originalName,
        mimeType,
        expectedSize
    );

    if (!isValidCourseMaterialPublicId(publicId, resourceType)) {
        throw createStorageError(
            "Invalid Cloudinary public identifier."
        );
    }

    if (
        !["raw", "video"].includes(resourceType) ||
        resourceType !== fileDefinition.resourceType
    ) {
        throw createStorageError(
            "Uploaded resource type does not match the file format."
        );
    }

    const expectedAssetFolder = getCourseMaterialAssetFolder(
        orgId,
        courseId
    );

    let resource;

    try {
        resource = await cloudinary.api.resource(
            publicId,
            {
                resource_type: resourceType,
                type: "authenticated"
            }
        );
    } catch (error) {
        if (
            error?.http_code === 404 ||
            error?.error?.http_code === 404
        ) {
            throw createStorageError(
                "Uploaded file was not found in Cloudinary.",
                HTTP_STATUS.NOT_FOUND,
                ERROR_CODES.RESOURCE_NOT_FOUND
            );
        }

        throw createStorageError(
            "Unable to verify the uploaded file with Cloudinary.",
            HTTP_STATUS.BAD_GATEWAY,
            ERROR_CODES.EXTERNAL_SERVICE_ERROR
        );
    }

    if (
        resource.public_id !== publicId ||
        resource.resource_type !== resourceType ||
        resource.type !== "authenticated"
    ) {
        throw createStorageError(
            "Cloudinary resource identity or delivery type could not be verified."
        );
    }

    /**
     * Dynamic folder mode exposes the organizational folder
     * separately from the public ID.
     *
     * Do not check whether public_id starts with the folder path.
     */
    if (resource.asset_folder !== expectedAssetFolder) {
        throw createStorageError(
            "Uploaded file does not belong to this course."
        );
    }

    if (resource.bytes !== expectedSize) {
        throw createStorageError(
            "Uploaded file size does not match the authorized upload."
        );
    }

    return {
        originalName,
        storageProvider: "cloudinary",
        storageKey: `${resourceType}:${resource.public_id}`,
        assetId: resource.asset_id || null,
        resourceType,
        mimeType,
        size: resource.bytes,
        checksum: null,
        format: resource.format || null
    };
};


/**
 * Generates a short-lived authenticated Cloudinary download URL.
 *
 * Authenticated resources are not exposed through ordinary
 * public delivery URLs.
 *
 * The generated URL is valid for five minutes.
 *
 * Raw public IDs already contain their file extension, so the
 * format argument is omitted for raw downloads to avoid adding
 * the extension a second time.
 *
 * @param {Object} options
 * @param {string} options.storageKey
 * @param {string} options.format
 *
 * @returns {Object}
 */
export const createCourseMaterialAccessUrl = ({
    storageKey,
    format
}) => {
    configureCloudinary();

    if (
        typeof storageKey !== "string" ||
        !storageKey.includes(":")
    ) {
        throw createStorageError(
            "Invalid course material storage reference."
        );
    }

    const separatorIndex = storageKey.indexOf(":");

    const resourceType = storageKey.slice(0, separatorIndex);
    const publicId = storageKey.slice(separatorIndex + 1);

    if (
        !["raw", "video"].includes(resourceType) ||
        !isValidCourseMaterialPublicId(publicId, resourceType)
    ) {
        throw createStorageError(
            "Invalid Cloudinary storage reference."
        );
    }

    if (
        resourceType === "video" &&
        (
            typeof format !== "string" ||
            !/^[a-z0-9]+$/i.test(format)
        )
    ) {
        throw createStorageError(
            "Invalid course material file format."
        );
    }

    const expiresAt = Math.floor(Date.now() / 1000) + 300;

    const downloadFormat = resourceType === "raw"
        ? undefined
        : format;

    const url = cloudinary.utils.private_download_url(
        publicId,
        downloadFormat,
        {
            resource_type: resourceType,
            type: "authenticated",
            expires_at: expiresAt
        }
    );

    return {
        url,
        expiresAt: new Date(expiresAt * 1000)
    };
};


/**
 * Deletes an authenticated Cloudinary course material.
 *
 * Public IDs are validated against the UUID format generated
 * by this module before a deletion request is sent.
 *
 * @param {string} storageKey
 * @returns {Promise<Object>}
 */
export const deleteCourseMaterialFile = async (storageKey) => {
    configureCloudinary();

    if (
        typeof storageKey !== "string" ||
        !storageKey.includes(":")
    ) {
        throw createStorageError(
            "Invalid course material storage reference."
        );
    }

    const separatorIndex = storageKey.indexOf(":");

    const resourceType = storageKey.slice(0, separatorIndex);
    const publicId = storageKey.slice(separatorIndex + 1);

    if (!isValidCourseMaterialPublicId(publicId, resourceType)) {
        throw createStorageError(
            "Course material storage reference is not permitted."
        );
    }

    try {
        const result = await cloudinary.uploader.destroy(
            publicId,
            {
                resource_type: resourceType,
                type: "authenticated",
                invalidate: true
            }
        );

        if (
            result.result !== "ok" &&
            result.result !== "not found"
        ) {
            throw createStorageError(
                "Cloudinary could not delete the course material.",
                HTTP_STATUS.BAD_GATEWAY,
                ERROR_CODES.EXTERNAL_SERVICE_ERROR
            );
        }

        return result;
    } catch (error) {
        if (error instanceof AppError) {
            throw error;
        }

        throw createStorageError(
            "Unable to delete the course material from Cloudinary.",
            HTTP_STATUS.BAD_GATEWAY,
            ERROR_CODES.EXTERNAL_SERVICE_ERROR
        );
    }
};